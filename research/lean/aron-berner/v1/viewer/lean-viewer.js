  /** Lean source with light, dependable highlighting. */
  function highlight(source) {
    var pattern = /(\/-[\s\S]*?-\/|--[^\n]*)|("(?:[^"\\]|\\.)*")|(\b\d+(?:\.\d+)?\b)|([A-Za-z_À-ɏͰ-Ͽ][\w'.!?À-ɏͰ-Ͽ₀-₉]*)|([ℕℤℚℝℂ])/g;
    var out = "", last = 0, match;
    while ((match = pattern.exec(source)) !== null) {
      out += escapeHtml(source.slice(last, match.index));
      var token = escapeHtml(match[0]);
      if (match[1]) out += '<span class="c">' + token + "</span>";
      else if (match[2]) out += '<span class="s">' + token + "</span>";
      else if (match[3]) out += '<span class="n">' + token + "</span>";
      else if (match[4] && match[4] === "sorry") out += '<span class="sorry">sorry</span>';
      else if (match[4] && KEYWORDS.indexOf(match[4]) >= 0) out += '<span class="k">' + token + "</span>";
      else if (match[5]) out += '<span class="t">' + token + "</span>";
      else out += token;
      last = match.index + match[0].length;
    }
    return out + escapeHtml(source.slice(last));
  }

