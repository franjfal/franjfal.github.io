  /**
   * A LaTeX statement as HTML MathJax can typeset: math is kept verbatim (with
   * $…$ turned into \(…\), which the site's MathJax expects) and the commonest
   * text-mode commands become their HTML equivalents.
   */
  function latexToHtml(source) {
    source = relabel(source || "");
    var pieces = [];
    var pattern = /(\$\$[\s\S]+?\$\$|\$(?:[^$\\]|\\.)+?\$|\\\[[\s\S]+?\\\]|\\\([\s\S]+?\\\)|\\begin\{(equation\*?|align\*?|gather\*?|multline\*?|eqnarray\*?)\}[\s\S]+?\\end\{\2\})/g;
    var last = 0, match;
    while ((match = pattern.exec(source)) !== null) {
      pieces.push(textMode(source.slice(last, match.index)));
      var math = match[0];
      if (math.indexOf("$$") === 0) math = "\\[" + math.slice(2, -2) + "\\]";
      else if (math.charAt(0) === "$") math = "\\(" + math.slice(1, -1) + "\\)";
      pieces.push(escapeHtml(math));
      last = match.index + match[0].length;
    }
    pieces.push(textMode(source.slice(last)));
    return pieces.join("");
  }

  function textMode(text) {
    var html = escapeHtml(text);
    var replace = function (pattern, value) { html = html.replace(pattern, value); };
    for (var i = 0; i < 3; i += 1) {
      replace(/\\(?:emph|textit|textsl)\{([^{}]*)\}/g, "<em>$1</em>");
      replace(/\\textbf\{([^{}]*)\}/g, "<strong>$1</strong>");
      replace(/\\(?:text|textrm|textup|mbox)\{([^{}]*)\}/g, "$1");
    }
    replace(/\\begin\{(?:enumerate|itemize)\}(?:\[[^\]]*\])?/g, "<ol>");
    replace(/\\end\{(?:enumerate|itemize)\}/g, "</ol>");
    replace(/\\item(?:\[([^\]]*)\])?/g, function (_, label) { return "<li>" + (label ? "<b>" + label + "</b> " : ""); });
    replace(/\\(?:eq)?ref\{([^{}]*)\}/g, "<span class=\"lnv-ref\">($1)</span>");
    replace(/\\cite(?:\[[^\]]*\])?\{([^{}]*)\}/g, "[$1]");
    replace(/\\(?:label|index)\{[^{}]*\}/g, "");
    replace(/~/g, "&nbsp;");
    replace(/\\\\/g, "<br>");
    replace(/\\(?:quad|qquad|noindent|smallskip|medskip|bigskip|par)\b/g, " ");
    replace(/``|''/g, "\"");
    return html;
  }

