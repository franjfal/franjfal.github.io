  var LABELS = [];

  function setLabels(statements) {
    LABELS = (statements || []).filter(function (statement) { return statement.label && statement.number; }).map(function (statement) {
      var label = statement.label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      return {
        named: new RegExp("(?:\\b" + statement.display + "\\s+|" + statement.display + "~)(?:\\{lit\\})?`?" + label + "`?", "g"),
        ref: new RegExp("\\\\(?:eq|c)?ref\\{" + label + "\\}", "g"),
        bare: new RegExp("(?:\\{lit\\})?`" + label + "`|\\b" + label + "\\b", "g"),
        display: statement.display + " " + statement.number,
        number: statement.number
      };
    });
  }

  function relabel(text) {
    var out = String(text || "");
    LABELS.forEach(function (item) {
      out = out.replace(item.named, item.display).replace(item.ref, item.number).replace(item.bare, item.display);
    });
    return out;
  }

  /** A statement's optional title as plain words: no braces, citations as [DG]. */
  function titleHtml(title) {
    return textMode(relabel(title || "")).replace(/[{}]/g, "").replace(/\s+/g, " ").trim();
  }

  /**
   * A Lean docstring as HTML: Markdown emphasis and code, Verso's math
   * ($`x` inline, $$`x` displayed) as MathJax delimiters, and {name}`x`
   * references as code.
   */
  function docToHtml(source) {
    var html = escapeHtml(relabel(source || ""));
    html = html.replace(/\$\$`([^`]*)`/g, function (_, math) { return "\\[" + math + "\\]"; });
    html = html.replace(/\$`([^`]*)`/g, function (_, math) { return "\\(" + math + "\\)"; });
    html = html.replace(/\{[a-z]+(?:\s[^}]*)?\}`([^`]*)`/g, "<code>$1</code>");
    html = html.replace(/`([^`]+)`/g, "<code>$1</code>");
    html = html.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
    html = html.replace(/(^|[^*])\*([^*\s][^*]*)\*/g, "$1<em>$2</em>");
    return html.replace(/\n{2,}/g, "<br><br>");
  }

  var MATHJAX_URL = "https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-chtml.js";

  /**
   * Typeset the statements with MathJax. The site loads MathJax for its own
   * pages, but a page script may replace the global with a configuration
   * object after MathJax started, which leaves nothing to typeset content
   * added later. Then this page loads its own instance, told not to scan the
   * rest of the page again.
   */
  function typeset(node) {
    var mathjax = window.MathJax;
    var run = function () { window.MathJax.typesetPromise([node]).catch(function () { /* leave the source visible */ }); };
    if (mathjax && typeof mathjax.typesetPromise === "function") {
      if (mathjax.startup && mathjax.startup.promise) mathjax.startup.promise.then(run);
      else run();
      return;
    }
    if (mathjax && mathjax.startup && mathjax.startup.promise) {
      mathjax.startup.promise.then(run);
      return;
    }
    var pending = document.querySelector("script[data-lean-mathjax]");
    if (pending) { pending.addEventListener("load", function () { window.MathJax.startup.promise.then(run); }); return; }
    var configuration = mathjax && !mathjax.version ? mathjax : {};
    // The article's macros need \newcommand, which a site's own package list may leave out.
    var tex = Object.assign({}, configuration.tex || {}, { packages: { "[+]": ["ams", "newcommand"] } });
    window.MathJax = Object.assign({}, configuration, { tex: tex, startup: Object.assign({}, configuration.startup || {}, { typeset: false }) });
    var script = document.createElement("script");
    script.src = MATHJAX_URL;
    script.async = true;
    script.setAttribute("data-lean-mathjax", "");
    script.addEventListener("load", function () { window.MathJax.startup.promise.then(run); });
    document.head.appendChild(script);
  }

