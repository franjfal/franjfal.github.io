#!/usr/bin/env python3
"""Check the Lean formalizations Proofline published into this site.

GitHub Pages never runs Lean, Lake, Mathlib or Verso: every page under
research/lean/ was verified and generated by Proofline and committed as static
files. This check only confirms that what is about to be deployed is what
Proofline exported:

- every public version folder (vN/) still matches its MANIFEST.json, file by
  file (a published version is permanent and is never edited by hand);
- every link from a version's formalization.json into its Verso
  documentation, and its downloadable Lean project, exists;
- versions.json, the main page and _data/lean_formalizations.json agree on
  which version is the latest.

Usage: python3 scripts/check_lean_publications.py [site root]
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

BASE = "research/lean"


def check(root: Path) -> list[str]:
    errors: list[str] = []
    base = root / BASE
    index_path = root / "_data" / "lean_formalizations.json"
    try:
        index = json.loads(index_path.read_text(encoding="utf-8")) if index_path.exists() else {"items": []}
    except json.JSONDecodeError as exc:
        return [f"{index_path}: invalid JSON ({exc})"]
    listed = {item.get("slug"): item for item in index.get("items", [])}
    slugs = sorted(path.name for path in base.iterdir() if path.is_dir() and not path.name.startswith(".")) if base.is_dir() else []
    for slug in slugs:
        folder = base / slug
        for leftover in folder.glob(".proofline-staging-*"):
            errors.append(f"{leftover}: an unfinished export was left behind; export again from Proofline")
        versions_path = folder / "versions.json"
        try:
            versions = json.loads(versions_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            errors.append(f"{versions_path}: missing or invalid ({exc})")
            continue
        numbers = sorted(int(match.group(1)) for path in folder.iterdir() if (match := re.fullmatch(r"v(\d+)", path.name)) and path.is_dir())
        listed_numbers = sorted(item["version"] for item in versions.get("versions", []))
        if numbers != listed_numbers:
            errors.append(f"{versions_path}: lists versions {listed_numbers} but the folder has {numbers}")
        latest = versions.get("latest")
        if latest != (max(numbers) if numbers else None):
            errors.append(f"{versions_path}: latest is v{latest}, expected v{max(numbers) if numbers else None}")
        main_page = folder / "index.md"
        if not main_page.exists() or f'lean_base: "/{BASE}/{slug}/v{latest}/"' not in main_page.read_text(encoding="utf-8"):
            errors.append(f"{main_page}: the main page must show the latest version, v{latest}")
        if slug not in listed:
            errors.append(f"{index_path}: {slug} is published but not listed")
        elif listed[slug].get("version") != latest:
            errors.append(f"{index_path}: lists {slug} v{listed[slug].get('version')}, the latest is v{latest}")
        for number in numbers:
            errors.extend(check_version(folder / f"v{number}", slug, number))
    for slug in listed:
        if slug not in slugs:
            errors.append(f"{index_path}: lists {slug}, which has no folder under {BASE}/")
    return errors


def check_version(directory: Path, slug: str, number: int) -> list[str]:
    errors: list[str] = []
    try:
        manifest = json.loads((directory / "MANIFEST.json").read_text(encoding="utf-8"))
        data = json.loads((directory / "formalization.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return [f"{directory}: MANIFEST.json or formalization.json missing or invalid ({exc})"]
    expected = {entry["path"]: entry["sha256"] for entry in manifest.get("files", [])}
    present = {path.relative_to(directory).as_posix() for path in directory.rglob("*") if path.is_file()} - {"MANIFEST.json", "index.md"}
    for path in sorted(present - set(expected)):
        errors.append(f"{directory / path}: not part of the published version")
    for path, digest in sorted(expected.items()):
        file = directory / path
        if not file.is_file():
            errors.append(f"{file}: missing from the published version")
        elif hashlib.sha256(file.read_bytes()).hexdigest() != digest:
            errors.append(f"{file}: changed after it was published")
    if data.get("slug") != slug or data.get("version") != number:
        errors.append(f"{directory}/formalization.json: describes {data.get('slug')} v{data.get('version')}")
    download = (data.get("links") or {}).get("download")
    if not download or not (directory / download).is_file():
        errors.append(f"{directory}: the Lean project {download} is missing")
    for item in data.get("declarations", []) + data.get("modules", []):
        target = (item.get("docs_url") or "").split("#", 1)[0]
        if target and not (directory / target / "index.html").is_file() and not (directory / target).is_file():
            errors.append(f"{directory}: {item.get('name')} links to {target}, which is not in the documentation")
    return errors


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    errors = check(root)
    if errors:
        print("Lean publications are inconsistent:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    count = len([path for path in (root / BASE).iterdir() if path.is_dir()]) if (root / BASE).is_dir() else 0
    print(f"Lean publications: {count} formalization(s) checked.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
