#!/usr/bin/env python3
"""Subset GNU FreeSans/FreeSerif (Helvetica/Times metric clones with wide Unicode coverage) for the PDFs.

jsPDF's built-in Helvetica and Times cannot print Σ, ∞, ≤, → or √, and this case is full of them.
The subsets keep Latin, Greek, punctuation, arrows and mathematical operators, and are written as a
classic script (fonts/sf-fonts.js) so that the generator also works from a local folder without a server.

Source: TeX Live, fonts/truetype/public/gnu-freefont (GNU GPL v3 with the font exception: documents
that embed these fonts are not affected by the GPL). The licence travels with the files in fonts/.

Usage: python3 tools/subset_fonts.py [path to gnu-freefont]
"""
import base64
import io
import pathlib
import subprocess
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(
    subprocess.check_output(["kpsewhich", "-var-value", "TEXMFDIST"], text=True).strip()
) / "fonts/truetype/public/gnu-freefont"

FACES = {  # jsPDF family name, style -> file
    ("SFSans", "normal"): "FreeSans.ttf",
    ("SFSans", "bold"): "FreeSansBold.ttf",
    ("SFSans", "italic"): "FreeSansOblique.ttf",
    ("SFSerif", "normal"): "FreeSerif.ttf",
    ("SFSerif", "bold"): "FreeSerifBold.ttf",
    ("SFSerif", "italic"): "FreeSerifItalic.ttf",
    ("SFSerif", "bolditalic"): "FreeSerifBoldItalic.ttf",
}
RANGES = [
    (0x20, 0x7E), (0xA0, 0x17F),          # Latin, Latin-1, Latin Extended-A
    (0x370, 0x3FF),                       # Greek
    (0x2010, 0x2044), (0x2070, 0x209F),   # punctuation, super/subscripts
    (0x20AC, 0x20AC), (0x2116, 0x2122),   # euro, numero, trade mark
    (0x2190, 0x21FF),                     # arrows
    (0x2200, 0x22FF),                     # mathematical operators
    (0x2308, 0x230B),                     # ceiling and floor
    (0x25A0, 0x25FF), (0x2600, 0x26FF),   # geometric shapes, miscellaneous symbols (★)
    (0x2713, 0x2717),                     # check marks
]


def unicodes():
    out = []
    for lo, hi in RANGES:
        out.extend(range(lo, hi + 1))
    return out


def main():
    lines = [
        "/* Subsets of GNU FreeSans and FreeSerif (GNU GPL v3 with font exception; see fonts/COPYING-FreeFont.txt).",
        " * Generated by tools/subset_fonts.py: do not edit. */",
        "(function (root) {",
        "  root.SFFonts = root.SFFonts || {};",
    ]
    total = 0
    for (family, style), name in FACES.items():
        font = TTFont(SRC / name)
        options = subset.Options()
        options.layout_features = []
        options.notdef_outline = True
        options.name_IDs = ["*"]
        options.drop_tables += ["GSUB", "GPOS", "GDEF"]
        sub = subset.Subsetter(options)
        sub.populate(unicodes=unicodes())
        sub.subset(font)
        buf = io.BytesIO()
        font.save(buf)
        data = buf.getvalue()
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        lines.append(f'  root.SFFonts["{family}-{style}"] = {{ family: "{family}", style: "{style}", file: "{family}-{style}.ttf", data: "{b64}" }};')
        print(f"{family:8s} {style:10s} {name:26s} {len(data) / 1024:7.1f} KB")
    lines.append("})(typeof window !== 'undefined' ? window : globalThis);")
    (HERE / "fonts" / "sf-fonts.js").write_text("\n".join(lines) + "\n")
    copying = SRC.parent.parent.parent.parent / "doc/fonts/gnu-freefont/COPYING"
    licence = copying.read_text() if copying.exists() else "GNU GPL v3 with font exception"
    (HERE / "fonts" / "COPYING-FreeFont.txt").write_text(
        "The fonts embedded in sf-fonts.js are subsets of GNU FreeFont (FreeSans, FreeSerif),\n"
        "https://www.gnu.org/software/freefont/. Font exception: as a special exception, if you create a\n"
        "document which uses this font, and embed this font or unaltered portions of this font into the\n"
        "document, this font does not by itself cause the resulting document to be covered by the GNU\n"
        "General Public License.\n\n" + licence)
    print(f"total {total / 1024:.0f} KB -> fonts/sf-fonts.js")


if __name__ == "__main__":
    main()
